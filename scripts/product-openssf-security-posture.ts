function readText(path: string): string {
  return readFileSync(resolve(root, path), 'utf8')
}

function sha256(text: string): string {
  return createHash('sha256').update(text).digest('hex')
}

function check(label: string, ok: boolean, detail: string): PostureCheck {
  return { label, ok, detail }
}

function usesLines(text: string): string[] {
  return text
    .split(/\r?\n/)
    .map((line) => line.trim())
    .filter((line) => line.startsWith('uses: '))
}

function allActionsPinned(texts: string[]): boolean {
  const lines = texts.flatMap(usesLines)
  return lines.length > 0 && lines.every((line) => /@[a-f0-9]{40}(?:\s|$)/i.test(line))
}

function sectionContains(text: string, sectionHeader: string, expected: string[]): boolean {
  const lines = text.split(/\r?\n/)
  const headerIndex = lines.findIndex((line) => line.trim() === sectionHeader)
  if (headerIndex < 0) {
    return false
  }

  const nextHeaderIndex = lines.findIndex((line, index) => index > headerIndex && /^\s{0,4}[A-Za-z0-9_-]+:\s*$/.test(line))
  const section = lines.slice(headerIndex, nextHeaderIndex < 0 ? lines.length : nextHeaderIndex).join('\n')
  return expected.every((needle) => section.includes(needle))
}

