  const codeqlWorkflowPresent = codeqlWorkflowExists && /github\/codeql-action\/init@/i.test(codeqlWorkflow) && /github\/codeql-action\/analyze@/i.test(codeqlWorkflow)
  const codeqlActionsPinned = codeqlWorkflowPresent && allActionsPinned([codeqlWorkflow])
  const codeqlPermissionsScoped = /security-events:\s+write/.test(codeqlWorkflow) && /contents:\s+read/.test(codeqlWorkflow) && !/\bwrite-all\b/i.test(codeqlWorkflow)
  const codeqlAnalyzesJavaScriptTypeScript = /javascript-typescript/.test(codeqlWorkflow)
