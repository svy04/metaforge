import { createHash } from 'node:crypto'
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'

type Check = {
  label: string
  ok: boolean
  detail: string
}

type BenchmarkTaskManifestEntry = {
  benchmarkTaskId: string
  benchmarkFamily: string
  sourceEvidencePath: string
  sourceEvidenceSha256: string
  taskType: string
  externalBenchmarkAnalog: string
  requiredEvidence: string[]
  terminalOutcomeClass: string
  protectedActionRequired: boolean
  protectedActionExecuted: boolean
  externalBenchmarkResultClaimed: boolean
  providerCallsPerformed: number
  liveModelCallsPerformed: number
  externalCallsPerformed: number
}

type BenchmarkReadinessReport = {
  mode: string
  benchmarkManifestPath: string
  benchmarkManifestSha256: string
  benchmarkTaskCount: number
  externalBenchmarkRunPerformed: boolean
  externalBenchmarkResultClaimed: boolean
}

type ExternalBenchmarkBoundaryReport = {
  mode: string
  externalBenchmarkExecutionAuthorized: boolean
  externalBenchmarkExecutionPerformed: boolean
  externalBenchmarkResultClaimAllowed: boolean
  protectedActionsExecuted: unknown[]
}

type LocalBenchmarkTaskResult = {
  benchmarkTaskId: string
  benchmarkFamily: string
  sourceEvidencePath: string
  sourceEvidenceExists: boolean
  expectedSourceEvidenceSha256: string
  actualSourceEvidenceSha256: string | null
  sourceEvidenceHashMatches: boolean
  requiredEvidenceCount: number
  terminalOutcomeClass: string
  localHarnessStatus: 'valid_local_evidence' | 'classified_environment_blocked' | 'failed_local_evidence'
  protectedActionRequired: boolean
  protectedActionExecuted: boolean
  externalBenchmarkResultClaimed: boolean
  providerCallsPerformed: number
  liveModelCallsPerformed: number
  externalCallsPerformed: number
}

type LocalBenchmarkHarnessReport = {
  generatedAt: string
  mode: 'local_no_provider_benchmark_replay_harness'
  sourceBenchmarkReadinessPath: string
  sourceBenchmarkManifestPath: string
  sourceBenchmarkTaskCount: number
  sourceBenchmarkManifestSha256: string
  sourceExternalBenchmarkBoundaryPath: string
  providerCallsPerformed: []
  liveModelCallsPerformed: []
  externalCallsPerformed: []
  protectedActionsExecuted: []
  externalBenchmarkExecutionPerformed: false
  externalBenchmarkResultClaimed: false
  localBenchmarkResultPath: string
  localBenchmarkResultSha256: string
  localBenchmarkTaskResults: LocalBenchmarkTaskResult[]
  statusSummary: {
    validLocalEvidenceTasks: number
    classifiedBlockedTasks: number
    failedTasks: number
  }
  harnessChecks: Check[]
  claimBoundary: string
}

const root = process.cwd()
const docsDir = resolve(root, 'docs/product-quality')
const reportsDir = resolve(root, 'reports')
const benchmarkReadinessPath = 'docs/product-quality/benchmark-readiness-matrix.json'
const externalBoundaryPath = 'docs/product-quality/external-benchmark-boundary-report.json'
const resultPath = 'reports/openclaude-local-benchmark-results.jsonl'

function readJson<T>(path: string): T {
  return JSON.parse(readFileSync(resolve(root, path), 'utf8')) as T
}

function fileSha256(path: string): string {
  return createHash('sha256').update(readFileSync(resolve(root, path))).digest('hex')
}

function textSha256(text: string): string {
  return createHash('sha256').update(text).digest('hex')
}

function check(label: string, ok: boolean, detail: string): Check {
  return { label, ok, detail }
}

function readManifest(path: string): BenchmarkTaskManifestEntry[] {
  const text = readFileSync(resolve(root, path), 'utf8').trim()
  if (text.length === 0) {
    return []
  }
  return text.split(/\r?\n/).map((line) => JSON.parse(line) as BenchmarkTaskManifestEntry)
}

function classifyTask(entry: BenchmarkTaskManifestEntry, sourceEvidenceExists: boolean, sourceEvidenceHashMatches: boolean): LocalBenchmarkTaskResult['localHarnessStatus'] {
  if (!sourceEvidenceExists || !sourceEvidenceHashMatches || entry.protectedActionExecuted || entry.externalBenchmarkResultClaimed) {
    return 'failed_local_evidence'
  }
  if (entry.terminalOutcomeClass.includes('blocked') || entry.terminalOutcomeClass.includes('unknown')) {
    return 'classified_environment_blocked'
  }
  return 'valid_local_evidence'
}

function writeMarkdown(report: LocalBenchmarkHarnessReport): void {
  const taskRows = report.localBenchmarkTaskResults
    .map((task) => `| \`${task.benchmarkTaskId}\` | \`${task.localHarnessStatus}\` | \`${task.sourceEvidenceHashMatches}\` | \`${task.protectedActionExecuted}\` | \`${task.externalBenchmarkResultClaimed}\` | \`${task.terminalOutcomeClass}\` |`)
    .join('\n')
  const checkRows = report.harnessChecks
    .map((item) => `| ${item.label} | \`${item.ok}\` | ${item.detail} |`)
    .join('\n')

  const markdown = `# Local Benchmark Harness Report

Generated by: \`bun run product:local-benchmark-harness\`

## Claim Boundary

- This is a local no-provider replay harness for OpenClaude's benchmark task manifest.
- It validates source evidence hashes and task-result structure only.
- It does not run SWE-bench, OpenHands Benchmarks, providers, live models, external services, containers, hosted CI, deploy, publish, launch, or external benchmark evaluation.
- It does not claim external benchmark results, external validation, release readiness, production readiness, public readiness, or autonomous reliability.

## Summary

- mode: \`${report.mode}\`
- source_benchmark_manifest_path: \`${report.sourceBenchmarkManifestPath}\`
- source_benchmark_manifest_sha256: \`${report.sourceBenchmarkManifestSha256}\`
- source_benchmark_task_count: \`${report.sourceBenchmarkTaskCount}\`
- local_benchmark_result_path: \`${report.localBenchmarkResultPath}\`
- local_benchmark_result_sha256: \`${report.localBenchmarkResultSha256}\`
- valid_local_evidence_tasks: \`${report.statusSummary.validLocalEvidenceTasks}\`
- classified_blocked_tasks: \`${report.statusSummary.classifiedBlockedTasks}\`
- failed_tasks: \`${report.statusSummary.failedTasks}\`
- external_benchmark_execution_performed: \`${report.externalBenchmarkExecutionPerformed}\`
- external_benchmark_result_claimed: \`${report.externalBenchmarkResultClaimed}\`
- provider_calls_performed: \`${report.providerCallsPerformed.length}\`
- live_model_calls_performed: \`${report.liveModelCallsPerformed.length}\`
- external_calls_performed: \`${report.externalCallsPerformed.length}\`
- protected_actions_executed: \`${report.protectedActionsExecuted.length}\`

## Task Results

| Task | Local Harness Status | Hash Matches | Protected Action Executed | External Result Claimed | Terminal Outcome |
| --- | --- | --- | --- | --- | --- |
${taskRows}

## Checks

| Check | Result | Detail |
| --- | --- | --- |
${checkRows}
`

  writeFileSync(resolve(docsDir, 'local-benchmark-harness-report.md'), markdown)
}

function main(): void {
  mkdirSync(docsDir, { recursive: true })
  mkdirSync(reportsDir, { recursive: true })

  const readiness = readJson<BenchmarkReadinessReport>(benchmarkReadinessPath)
  const boundary = readJson<ExternalBenchmarkBoundaryReport>(externalBoundaryPath)
  const manifestEntries = readManifest(readiness.benchmarkManifestPath)

  const taskResults = manifestEntries.map((entry): LocalBenchmarkTaskResult => {
    const sourceEvidenceExists = existsSync(resolve(root, entry.sourceEvidencePath))
    const actualSourceEvidenceSha256 = sourceEvidenceExists ? fileSha256(entry.sourceEvidencePath) : null
    const sourceEvidenceHashMatches = actualSourceEvidenceSha256 === entry.sourceEvidenceSha256
    return {
      benchmarkTaskId: entry.benchmarkTaskId,
      benchmarkFamily: entry.benchmarkFamily,
      sourceEvidencePath: entry.sourceEvidencePath,
      sourceEvidenceExists,
      expectedSourceEvidenceSha256: entry.sourceEvidenceSha256,
      actualSourceEvidenceSha256,
      sourceEvidenceHashMatches,
      requiredEvidenceCount: entry.requiredEvidence.length,
      terminalOutcomeClass: entry.terminalOutcomeClass,
      localHarnessStatus: classifyTask(entry, sourceEvidenceExists, sourceEvidenceHashMatches),
      protectedActionRequired: entry.protectedActionRequired,
      protectedActionExecuted: entry.protectedActionExecuted,
      externalBenchmarkResultClaimed: entry.externalBenchmarkResultClaimed,
      providerCallsPerformed: entry.providerCallsPerformed,
      liveModelCallsPerformed: entry.liveModelCallsPerformed,
      externalCallsPerformed: entry.externalCallsPerformed,
    }
  })

  const resultText = `${taskResults.map((result) => JSON.stringify(result)).join('\n')}\n`
  writeFileSync(resolve(root, resultPath), resultText)
  const resultSha256 = textSha256(resultText)

  const statusSummary = {
    validLocalEvidenceTasks: taskResults.filter((task) => task.localHarnessStatus === 'valid_local_evidence').length,
    classifiedBlockedTasks: taskResults.filter((task) => task.localHarnessStatus === 'classified_environment_blocked').length,
    failedTasks: taskResults.filter((task) => task.localHarnessStatus === 'failed_local_evidence').length,
  }
  const expectedBlockedTaskCount = taskResults.filter((task) => (
    task.terminalOutcomeClass.includes('blocked') || task.terminalOutcomeClass.includes('unknown')
  )).length

  const checks = [
    check('benchmark readiness report is local no-provider', readiness.mode === 'local_no_provider_benchmark_readiness_matrix', readiness.mode),
    check('external benchmark boundary keeps execution blocked', boundary.mode === 'local_no_provider_external_benchmark_boundary' && !boundary.externalBenchmarkExecutionAuthorized && !boundary.externalBenchmarkExecutionPerformed, boundary.mode),
    check('manifest hash matches readiness report', fileSha256(readiness.benchmarkManifestPath) === readiness.benchmarkManifestSha256, readiness.benchmarkManifestPath),
    check('manifest task count matches readiness report', manifestEntries.length === readiness.benchmarkTaskCount, `${manifestEntries.length}/${readiness.benchmarkTaskCount}`),
    check('task ids are unique', new Set(taskResults.map((task) => task.benchmarkTaskId)).size === taskResults.length, `${taskResults.length} tasks`),
    check('source evidence exists for every task', taskResults.every((task) => task.sourceEvidenceExists), `${taskResults.filter((task) => task.sourceEvidenceExists).length}/${taskResults.length}`),
    check('source evidence hashes match every task', taskResults.every((task) => task.sourceEvidenceHashMatches), `${taskResults.filter((task) => task.sourceEvidenceHashMatches).length}/${taskResults.length}`),
    check('task records do not perform provider/live/external calls', taskResults.every((task) => task.providerCallsPerformed === 0 && task.liveModelCallsPerformed === 0 && task.externalCallsPerformed === 0), 'call counts=0'),
    check('task records execute no protected actions', taskResults.every((task) => task.protectedActionExecuted === false), 'protectedActionExecuted=false'),
    check('task records claim no external benchmark result', taskResults.every((task) => task.externalBenchmarkResultClaimed === false), 'externalBenchmarkResultClaimed=false'),
    check('blocked or unknown outcomes are classified instead of hidden', statusSummary.classifiedBlockedTasks === expectedBlockedTaskCount, `${statusSummary.classifiedBlockedTasks}/${expectedBlockedTaskCount} classified blocked`),
    check('local harness has no failed task evidence', statusSummary.failedTasks === 0, `${statusSummary.failedTasks} failed`),
    check('result JSONL hash is recorded', resultSha256.length === 64, resultSha256),
  ]

  const report: LocalBenchmarkHarnessReport = {
    generatedAt: new Date().toISOString(),
    mode: 'local_no_provider_benchmark_replay_harness',
    sourceBenchmarkReadinessPath: benchmarkReadinessPath,
    sourceBenchmarkManifestPath: readiness.benchmarkManifestPath,
    sourceBenchmarkTaskCount: readiness.benchmarkTaskCount,
    sourceBenchmarkManifestSha256: readiness.benchmarkManifestSha256,
    sourceExternalBenchmarkBoundaryPath: externalBoundaryPath,
    providerCallsPerformed: [],
    liveModelCallsPerformed: [],
    externalCallsPerformed: [],
    protectedActionsExecuted: [],
    externalBenchmarkExecutionPerformed: false,
    externalBenchmarkResultClaimed: false,
    localBenchmarkResultPath: resultPath,
    localBenchmarkResultSha256: resultSha256,
    localBenchmarkTaskResults: taskResults,
    statusSummary,
    harnessChecks: checks,
    claimBoundary: 'Local benchmark harness evidence is internal no-provider replay evidence only. It does not execute external benchmarks, providers, live models, external services, containers, hosted CI, deploy, publish, launch, or make release/public/production/external/autonomous reliability claims.',
  }

  writeFileSync(resolve(docsDir, 'local-benchmark-harness-report.json'), `${JSON.stringify(report, null, 2)}\n`)
  writeMarkdown(report)

  for (const item of checks) {
    console.log(`${item.ok ? 'PASS' : 'FAIL'}: ${item.label} (${item.detail})`)
  }
  const failed = checks.filter((item) => !item.ok)
  console.log('')
  if (failed.length > 0) {
    console.error(`RESULT: FAIL (${failed.length} failed checks)`)
    process.exit(1)
  }
  console.log('RESULT: PASS')
  console.log(`local_benchmark_result_path=${resultPath}`)
  console.log(`local_benchmark_task_count=${taskResults.length}`)
  console.log(`local_benchmark_valid_tasks=${statusSummary.validLocalEvidenceTasks}`)
  console.log(`local_benchmark_blocked_tasks=${statusSummary.classifiedBlockedTasks}`)
  console.log('external_benchmark_execution_performed=false')
  console.log('external_benchmark_result_claimed=false')
  console.log('provider_calls_performed=0')
  console.log('live_model_calls_performed=0')
  console.log('external_calls_performed=0')
}

main()
