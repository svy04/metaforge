import { createHash } from 'node:crypto'
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'

type Check = {
  label: string
  ok: boolean
  detail: string
}

type BenchmarkReadinessReport = {
  mode: string
  providerCallsPerformed: unknown[]
  liveModelCallsPerformed: unknown[]
  externalCallsPerformed: unknown[]
  protectedActionsExecuted: unknown[]
  externalBenchmarkRunPerformed: boolean
  externalBenchmarkResultClaimed: boolean
  benchmarkManifestPath: string
  benchmarkManifestSha256: string
  benchmarkTaskCount: number
  primarySourceInputs: Array<{
    sourceProject: string
    sourceUrl: string
    observedPattern: string
  }>
  readinessDimensions: Array<{
    id: string
    remainingGap: string
    protectedActionRequiredForGap: boolean
    protectedActionExecuted: boolean
  }>
  unresolvedGaps: Array<{
    id: string
    status: string
    protectedActionRequired: boolean
    protectedActionExecuted: boolean
    detail: string
  }>
  benchmarkReadinessChecks: Array<{
    label: string
    ok: boolean
  }>
}

type ProtectedActionAuthorization = {
  id: string
  title: string
  authorized: false
  requiredBeforeExecution: true
  currentStatus: 'explicit_owner_authorization_missing'
}

type BoundaryGap = {
  id: string
  category: string
  status: 'classified_unresolved'
  protectedActionRequired: boolean
  protectedActionExecuted: false
  requiredAuthorization: string
  forbiddenShortcut: string
}

type ExternalBenchmarkBoundaryReport = {
  generatedAt: string
  mode: 'local_no_provider_external_benchmark_boundary'
  sourceBenchmarkReadinessPath: string
  sourceBenchmarkReadinessSha256: string
  sourceBenchmarkTaskCount: number
  sourceBenchmarkManifestPath: string
  sourceBenchmarkManifestSha256: string
  providerCallsPerformed: []
  liveModelCallsPerformed: []
  externalCallsPerformed: []
  protectedActionsExecuted: []
  externalBenchmarkExecutionAuthorized: false
  externalBenchmarkExecutionPerformed: false
  externalBenchmarkResultClaimAllowed: false
  externalValidationClaimAllowed: false
  releaseReadinessClaimAllowed: false
  productionReadinessClaimAllowed: false
  publicReadinessClaimAllowed: false
  autonomousReliabilityClaimAllowed: false
  authorizationRequestPath: string
  protectedActionAuthorizations: ProtectedActionAuthorization[]
  boundaryGaps: BoundaryGap[]
  sourceReadinessUnresolvedGaps: BenchmarkReadinessReport['unresolvedGaps']
  boundaryChecks: Check[]
  claimBoundary: string
}

const root = process.cwd()
const docsDir = resolve(root, 'docs/product-quality')
const sourceReadinessPath = 'docs/product-quality/benchmark-readiness-matrix.json'
const authorizationRequestPath = 'docs/product-quality/external-benchmark-authorization-request.md'

function readJson<T>(path: string): T {
  return JSON.parse(readFileSync(resolve(root, path), 'utf8')) as T
}

function fileSha256(path: string): string {
  return createHash('sha256').update(readFileSync(resolve(root, path))).digest('hex')
}

function check(label: string, ok: boolean, detail: string): Check {
  return { label, ok, detail }
}

function writeMarkdown(report: ExternalBenchmarkBoundaryReport): void {
  const authorizationRows = report.protectedActionAuthorizations
    .map((item) => `| \`${item.id}\` | ${item.title} | \`${item.authorized}\` | \`${item.requiredBeforeExecution}\` | \`${item.currentStatus}\` |`)
    .join('\n')
  const gapRows = report.boundaryGaps
    .map((gap) => `| \`${gap.id}\` | ${gap.category} | \`${gap.status}\` | \`${gap.protectedActionRequired}\` | \`${gap.protectedActionExecuted}\` | ${gap.requiredAuthorization} | ${gap.forbiddenShortcut} |`)
    .join('\n')
  const checkRows = report.boundaryChecks
    .map((item) => `| ${item.label} | \`${item.ok}\` | ${item.detail} |`)
    .join('\n')

  const markdown = `# External Benchmark Boundary Report

Generated by: \`bun run product:external-benchmark-boundary\`

## Claim Boundary

- This report converts the local benchmark readiness matrix into a protected-action boundary map.
- It does not run SWE-bench, OpenHands Benchmarks, containers, remote runtimes, providers, live models, external services, hosted CI, deploy, publish, or launch.
- It does not claim external benchmark results, external validation, release readiness, production readiness, public readiness, or autonomous reliability.

## Summary

- mode: \`${report.mode}\`
- source_benchmark_readiness_path: \`${report.sourceBenchmarkReadinessPath}\`
- source_benchmark_readiness_sha256: \`${report.sourceBenchmarkReadinessSha256}\`
- source_benchmark_task_count: \`${report.sourceBenchmarkTaskCount}\`
- source_benchmark_manifest_path: \`${report.sourceBenchmarkManifestPath}\`
- source_benchmark_manifest_sha256: \`${report.sourceBenchmarkManifestSha256}\`
- external_benchmark_execution_authorized: \`${report.externalBenchmarkExecutionAuthorized}\`
- external_benchmark_execution_performed: \`${report.externalBenchmarkExecutionPerformed}\`
- external_benchmark_result_claim_allowed: \`${report.externalBenchmarkResultClaimAllowed}\`
- release_readiness_claim_allowed: \`${report.releaseReadinessClaimAllowed}\`
- production_readiness_claim_allowed: \`${report.productionReadinessClaimAllowed}\`
- public_readiness_claim_allowed: \`${report.publicReadinessClaimAllowed}\`
- autonomous_reliability_claim_allowed: \`${report.autonomousReliabilityClaimAllowed}\`
- protected_actions_executed: \`${report.protectedActionsExecuted.length}\`
- provider_calls_performed: \`${report.providerCallsPerformed.length}\`
- live_model_calls_performed: \`${report.liveModelCallsPerformed.length}\`
- external_calls_performed: \`${report.externalCallsPerformed.length}\`

## Protected Action Authorizations

| Action | Title | Authorized | Required Before Execution | Status |
| --- | --- | --- | --- | --- |
${authorizationRows}

## Boundary Gaps

| Gap | Category | Status | Protected Action Required | Protected Action Executed | Required Authorization | Forbidden Shortcut |
| --- | --- | --- | --- | --- | --- | --- |
${gapRows}

## Checks

| Check | Result | Detail |
| --- | --- | --- |
${checkRows}
`

  writeFileSync(resolve(docsDir, 'external-benchmark-boundary-report.md'), markdown)
}

function writeAuthorizationRequest(report: ExternalBenchmarkBoundaryReport): void {
  const authorizationList = report.protectedActionAuthorizations
    .map((item) => `- [ ] \`${item.id}\`: ${item.title} - currently \`${item.authorized}\``)
    .join('\n')
  const markdown = `# External Benchmark Authorization Request

## Current Decision

- external_benchmark_execution_authorized: \`${report.externalBenchmarkExecutionAuthorized}\`
- external_benchmark_execution_performed: \`${report.externalBenchmarkExecutionPerformed}\`
- protected_action_execution_authorized: \`false\`
- release_readiness_claim_allowed: \`${report.releaseReadinessClaimAllowed}\`
- production_readiness_claim_allowed: \`${report.productionReadinessClaimAllowed}\`
- public_readiness_claim_allowed: \`${report.publicReadinessClaimAllowed}\`
- autonomous_reliability_claim_allowed: \`${report.autonomousReliabilityClaimAllowed}\`

## Owner Decisions Required Before Real External Benchmark Execution

${authorizationList}

## Boundary

OpenClaude may keep generating internal local no-provider benchmark-readiness evidence. It may not execute external benchmarks, providers, live models, external services, containers, hosted CI, deploy, publish, launch, or external/public/release/production/autonomous claims without a separate explicit owner authorization.
`

  writeFileSync(resolve(root, authorizationRequestPath), markdown)
}

function main(): void {
  mkdirSync(docsDir, { recursive: true })

  const readiness = readJson<BenchmarkReadinessReport>(sourceReadinessPath)
  const sourceReadinessSha256 = fileSha256(sourceReadinessPath)

  const protectedActionAuthorizations: ProtectedActionAuthorization[] = [
    { id: 'external_dataset_access', title: 'Fetch or use external benchmark datasets', authorized: false, requiredBeforeExecution: true, currentStatus: 'explicit_owner_authorization_missing' },
    { id: 'container_runtime_setup', title: 'Start Docker/container or benchmark sandbox runtime', authorized: false, requiredBeforeExecution: true, currentStatus: 'explicit_owner_authorization_missing' },
    { id: 'provider_call', title: 'Call provider APIs during benchmark execution', authorized: false, requiredBeforeExecution: true, currentStatus: 'explicit_owner_authorization_missing' },
    { id: 'live_model_call', title: 'Call live models during benchmark execution', authorized: false, requiredBeforeExecution: true, currentStatus: 'explicit_owner_authorization_missing' },
    { id: 'external_service_call', title: 'Call remote benchmark, telemetry, or hosted evaluation services', authorized: false, requiredBeforeExecution: true, currentStatus: 'explicit_owner_authorization_missing' },
    { id: 'remote_runtime_access', title: 'Use remote runtime, worker, or hosted benchmark infrastructure', authorized: false, requiredBeforeExecution: true, currentStatus: 'explicit_owner_authorization_missing' },
    { id: 'hosted_ci_execution', title: 'Run hosted CI or publish benchmark artifacts through a remote repository', authorized: false, requiredBeforeExecution: true, currentStatus: 'explicit_owner_authorization_missing' },
    { id: 'external_validation_claim', title: 'Claim external validation from benchmark execution', authorized: false, requiredBeforeExecution: true, currentStatus: 'explicit_owner_authorization_missing' },
    { id: 'public_result_claim', title: 'Publish or publicly cite benchmark results', authorized: false, requiredBeforeExecution: true, currentStatus: 'explicit_owner_authorization_missing' },
    { id: 'release_readiness_claim', title: 'Claim release readiness from benchmark results', authorized: false, requiredBeforeExecution: true, currentStatus: 'explicit_owner_authorization_missing' },
    { id: 'production_readiness_claim', title: 'Claim production readiness from benchmark results', authorized: false, requiredBeforeExecution: true, currentStatus: 'explicit_owner_authorization_missing' },
    { id: 'autonomous_reliability_claim', title: 'Claim autonomous reliability from benchmark results', authorized: false, requiredBeforeExecution: true, currentStatus: 'explicit_owner_authorization_missing' },
  ]

  const boundaryGaps: BoundaryGap[] = [
    { id: 'external_dataset_access', category: 'external_benchmark_execution', status: 'classified_unresolved', protectedActionRequired: true, protectedActionExecuted: false, requiredAuthorization: 'Owner approval to fetch/use benchmark datasets.', forbiddenShortcut: 'Do not treat local readiness manifest as external benchmark execution.' },
    { id: 'container_runtime_setup', category: 'external_benchmark_execution', status: 'classified_unresolved', protectedActionRequired: true, protectedActionExecuted: false, requiredAuthorization: 'Owner approval for Docker/container/runtime setup.', forbiddenShortcut: 'Do not install or start benchmark runtimes in this gate.' },
    { id: 'provider_live_model_validation', category: 'provider_boundary', status: 'classified_unresolved', protectedActionRequired: true, protectedActionExecuted: false, requiredAuthorization: 'Owner approval for provider and live model calls.', forbiddenShortcut: 'Do not convert no-provider traces into provider-backed evidence.' },
    { id: 'remote_runtime_access', category: 'external_service_boundary', status: 'classified_unresolved', protectedActionRequired: true, protectedActionExecuted: false, requiredAuthorization: 'Owner approval for remote workers or benchmark services.', forbiddenShortcut: 'Do not call remote runtimes or services from the local gate.' },
    { id: 'hosted_ci_execution', category: 'source_control_boundary', status: 'classified_unresolved', protectedActionRequired: true, protectedActionExecuted: false, requiredAuthorization: 'Owner approval plus a real Git repository/remote boundary.', forbiddenShortcut: 'Do not claim hosted CI from local workflow inspection.' },
    { id: 'public_result_claim', category: 'claim_boundary', status: 'classified_unresolved', protectedActionRequired: true, protectedActionExecuted: false, requiredAuthorization: 'Owner approval after real external benchmark evidence exists.', forbiddenShortcut: 'Do not publish or cite external results from local readiness evidence.' },
    { id: 'release_readiness_claim', category: 'claim_boundary', status: 'classified_unresolved', protectedActionRequired: true, protectedActionExecuted: false, requiredAuthorization: 'Owner release decision after external evidence review.', forbiddenShortcut: 'Do not claim release readiness from this boundary report.' },
    { id: 'production_readiness_claim', category: 'claim_boundary', status: 'classified_unresolved', protectedActionRequired: true, protectedActionExecuted: false, requiredAuthorization: 'Owner production decision after protected evidence is complete.', forbiddenShortcut: 'Do not claim production readiness from this boundary report.' },
  ]

  const checks = [
    check('benchmark readiness report is local no-provider', readiness.mode === 'local_no_provider_benchmark_readiness_matrix', readiness.mode),
    check('benchmark readiness has task manifest evidence', readiness.benchmarkTaskCount >= 8 && readiness.benchmarkManifestSha256.length === 64, `${readiness.benchmarkTaskCount} tasks`),
    check('benchmark readiness did not run external benchmark', readiness.externalBenchmarkRunPerformed === false && readiness.externalBenchmarkResultClaimed === false, 'externalBenchmarkRunPerformed=false'),
    check('benchmark readiness performed no calls', readiness.providerCallsPerformed.length === 0 && readiness.liveModelCallsPerformed.length === 0 && readiness.externalCallsPerformed.length === 0, 'provider/live/external calls=0'),
    check('benchmark readiness executed no protected actions', readiness.protectedActionsExecuted.length === 0 && readiness.readinessDimensions.every((dimension) => dimension.protectedActionExecuted === false), 'protected actions=0'),
    check('source readiness checks pass', readiness.benchmarkReadinessChecks.every((item) => item.ok), `${readiness.benchmarkReadinessChecks.length} checks`),
    check('all protected authorizations default false', protectedActionAuthorizations.every((item) => item.authorized === false && item.requiredBeforeExecution), `${protectedActionAuthorizations.length} authorizations`),
    check('required boundary gaps are classified', ['external_dataset_access', 'container_runtime_setup', 'provider_live_model_validation', 'remote_runtime_access', 'hosted_ci_execution', 'public_result_claim', 'release_readiness_claim', 'production_readiness_claim'].every((id) => boundaryGaps.some((gap) => gap.id === id)), boundaryGaps.map((gap) => gap.id).join(',')),
    check('boundary gaps remain unexecuted', boundaryGaps.every((gap) => gap.status === 'classified_unresolved' && gap.protectedActionExecuted === false), `${boundaryGaps.length} gaps`),
    check('external benchmark execution remains blocked', true, 'externalBenchmarkExecutionAuthorized=false'),
  ]

  const report: ExternalBenchmarkBoundaryReport = {
    generatedAt: new Date().toISOString(),
    mode: 'local_no_provider_external_benchmark_boundary',
    sourceBenchmarkReadinessPath: sourceReadinessPath,
    sourceBenchmarkReadinessSha256: sourceReadinessSha256,
    sourceBenchmarkTaskCount: readiness.benchmarkTaskCount,
    sourceBenchmarkManifestPath: readiness.benchmarkManifestPath,
    sourceBenchmarkManifestSha256: readiness.benchmarkManifestSha256,
    providerCallsPerformed: [],
    liveModelCallsPerformed: [],
    externalCallsPerformed: [],
    protectedActionsExecuted: [],
    externalBenchmarkExecutionAuthorized: false,
    externalBenchmarkExecutionPerformed: false,
    externalBenchmarkResultClaimAllowed: false,
    externalValidationClaimAllowed: false,
    releaseReadinessClaimAllowed: false,
    productionReadinessClaimAllowed: false,
    publicReadinessClaimAllowed: false,
    autonomousReliabilityClaimAllowed: false,
    authorizationRequestPath,
    protectedActionAuthorizations,
    boundaryGaps,
    sourceReadinessUnresolvedGaps: readiness.unresolvedGaps,
    boundaryChecks: checks,
    claimBoundary: 'External benchmark boundary evidence is internal local no-provider evidence only. It does not execute external benchmarks, providers, live models, external services, containers, hosted CI, deploy, publish, launch, or make release/public/production/external/autonomous reliability claims.',
  }

  writeFileSync(resolve(docsDir, 'external-benchmark-boundary-report.json'), `${JSON.stringify(report, null, 2)}\n`)
  writeMarkdown(report)
  writeAuthorizationRequest(report)

  for (const item of checks) {
    console.log(`${item.ok ? 'PASS' : 'FAIL'}: ${item.label} (${item.detail})`)
  }
  const failed = checks.filter((item) => !item.ok)
  console.log('')
  if (failed.length > 0) {
    console.error(`RESULT: FAIL (${failed.length} failed checks)`)
    process.exit(1)
  }
  console.log('RESULT: PASS')
  console.log('external_benchmark_execution_authorized=false')
  console.log('external_benchmark_execution_performed=false')
  console.log('external_benchmark_result_claim_allowed=false')
  console.log(`protected_action_authorizations=${protectedActionAuthorizations.length}`)
  console.log(`boundary_gaps=${boundaryGaps.length}`)
  console.log('provider_calls_performed=0')
  console.log('live_model_calls_performed=0')
  console.log('external_calls_performed=0')
}

main()
